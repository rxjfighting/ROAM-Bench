"""Evaluate task episodes and save results after each completed task."""
import argparse
import dataclasses
import hashlib
import json
import os
from pathlib import Path
import time
from .dataset import dataset_identity, load_scene, spawn_for, scene_for
from .protocol import llm, taskset
from .enhanced_evidence import judge
ROOT = Path(__file__).resolve().parents[1]

def validate_initial_states(rows):
    values = []
    for row in rows:
        if not isinstance(row, (list, tuple)) or len(row) != 3:
            raise ValueError('An initial state must contain alias, state type, and Boolean value.')
        alias, kind, value = row
        if not isinstance(alias, str) or not alias or kind not in ('open', 'toggled') or type(value) is not bool:
            raise ValueError('Invalid initial state.')
        values.append((alias, kind, value))
    return tuple(values)

def save(path, document):
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_suffix('.tmp')
    temporary.write_text(json.dumps(document, ensure_ascii=False, indent=2) + '\n')
    temporary.replace(destination)

def source_identity():
    files = sorted(path for path in (ROOT / 'roam_bench').rglob('*') if path.is_file() and path.suffix in ('.py', '.json'))
    records = [(str(path.relative_to(ROOT)), hashlib.sha256(path.read_bytes()).hexdigest()) for path in files]
    return hashlib.sha256(json.dumps(records).encode()).hexdigest()

def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dataset', type=Path, default=ROOT.parent / 'dataset')
    parser.add_argument('--assets', type=Path, help='Directory containing scene_XXX asset folders.')
    parser.add_argument('--scene-cache', type=Path, default=Path('.roam-cache/scenes'),
                        help='Cache for task-scoped scene variants; shared assets stay unchanged.')
    parser.add_argument('--scene', help='Evaluate one scene; otherwise evaluate the full task set.')
    parser.add_argument('--task-id')
    parser.add_argument('--group', choices=['G1', 'G2', 'G3', 'G4', 'G5'])
    parser.add_argument('--limit', type=int, default=0, help='Maximum tasks across the selected scenes.')
    parser.add_argument('--model', default=os.environ.get('ROAM_BENCH_MODEL'))
    parser.add_argument('--base-url', default=os.environ.get('ROAM_BENCH_BASE_URL'))
    parser.add_argument('--output', type=Path, default=Path('results/evaluation.json'))
    parser.add_argument('--dry-run', action='store_true', help='Validate tasks without Isaac Sim or model calls.')
    parser.add_argument('--resume', action='store_true', help='Skip completed tasks with matching inputs and settings.')
    parser.add_argument('--max-output-tokens', type=int, default=llm.DEFAULT_OUTPUT_TOKENS)
    parser.add_argument('--temperature', type=float, default=0.0)
    parser.add_argument('--top-p', type=float, default=1.0)
    parser.add_argument('--reasoning-effort', default='max',
                        help='Highest reasoning level; supply the endpoint-specific value if it does not use max.')
    parser.add_argument('--transport-attempts', type=int, default=10)
    parser.add_argument('--timeout', type=float, default=120)
    parser.add_argument('--image-limit', type=int, default=50)
    parser.add_argument('--history-rounds', type=int, default=20)
    parser.add_argument('--retrieval-passes', type=int, default=2)
    parser.add_argument('--retrieval-images', type=int, default=12)
    parser.add_argument('--extra-rounds', type=int, default=8)
    parser.add_argument('--robot-asset', type=Path, help='G1 Inspire USD generated by build_robot_asset.py.')
    args = parser.parse_args(argv)
    if args.limit < 0 or args.extra_rounds < 1 or args.history_rounds < 1 or args.image_limit < 1:
        parser.error('Limits and round allowances must be positive; --limit may be zero.')
    manifest = json.loads((args.dataset / 'manifest.json').read_text())
    chosen = [row for row in manifest['tasks'] if (not args.scene or row['scene'] == args.scene) and (not args.task_id or row['task_id'] == args.task_id) and (not args.group or row['group'] == args.group)]
    if args.limit:
        chosen = chosen[:args.limit]
    if not chosen:
        parser.error('No tasks match the selection.')
    scenes = sorted({row['scene'] for row in chosen})
    scene_specs = {}
    for scene in scenes:
        scene_specs[scene] = load_scene(args.dataset, scene, args.assets)
    if args.dry_run:
        print(json.dumps({'benchmark': 'ROAM-Bench', 'tasks': len(chosen), 'scenes': len(scenes), 'reference_images_resolved': True, 'model_calls': 0, 'simulation_started': False}))
        return 0
    if args.assets is None or not args.model or (not args.base_url):
        parser.error('Evaluation requires --assets, --model, and --base-url.')
    if args.output.exists() and (not args.resume):
        parser.error('Output exists. Choose a fresh path or use --resume.')
    configuration = {key: str(value) if isinstance(value, Path) else value for key, value in vars(args).items() if key not in {'resume', 'dry_run', 'output', 'scene', 'task_id', 'group', 'limit'}}
    configuration['dataset_sha256'] = dataset_identity(args.dataset)
    configuration['source_sha256'] = source_identity()
    result = {'benchmark': 'ROAM-Bench', 'configuration': configuration, 'results': []}
    if args.resume and args.output.exists():
        result = json.loads(args.output.read_text())
        if result['configuration'] != configuration:
            raise ValueError('Resume requires identical code, dataset, model, and evaluation settings.')
    completed = {(row['scene'], row['task_id']) for row in result['results']}
    save(args.output, result)
    from .runtime import configure
    configure(args.robot_asset)
    from . import harness
    from .backend import ROAMBackend
    from .client import EvaluationClient
    client = EvaluationClient(base_url=args.base_url, model=args.model, max_tokens=args.max_output_tokens, temperature=args.temperature, top_p=args.top_p, reasoning_effort=args.reasoning_effort, timeout=args.timeout, retries=args.transport_attempts)
    sim = ROAMBackend(headless=True, width=1280, height=720)
    sim.set_render_quality(4, 4)
    sim.set_embodiment('humanoid')
    sim.set_place_mode('point')
    sim.set_interact(True)
    base_episode = harness.episode_for
    try:
        for scene in scenes:
            header, specs = scene_specs[scene]
            harness.HOUSE = header['scene']
            harness.TASKSET = str(args.dataset.resolve() / 'tasksets' / (scene + '.json'))
            selected_ids = {row['task_id'] for row in chosen if row['scene'] == scene}
            for spec in specs:
                identity = (scene, spec.task.task_id)
                if spec.task.task_id not in selected_ids or identity in completed:
                    continue
                harness.HOUSE = scene_for(header, spec, args.scene_cache)
                initial = validate_initial_states(spec.truth.get('initial_states', header.get('initial_states', [])))

                def episode_for(*values, **options):
                    episode = base_episode(*values, **options)
                    episode.initial_states = initial
                    episode.view_min_pixels = 16
                    episode.view_min_pixel_fraction = None
                    return episode
                harness.episode_for = episode_for
                from .runtime import bind_task
                bind_task(scene, spec)
                started = time.monotonic()
                usage_before = (client.prompt_tokens, client.completion_tokens)
                case = args.output.parent / 'episodes' / args.output.stem / scene / spec.task.task_id
                case.mkdir(parents=True, exist_ok=True)
                score, film, agent, meta = harness.run_model_episode(sim, spec, client, taskset.TIER_REQUIRED.get(spec.family, 'plan'), spec.task.max_steps, args.extra_rounds, spawn_for(header, spec), vision_on=True, vision_keep=args.history_rounds, refer='pixel', sensor=True, mark_pixels='video', vision_mime='image/jpeg', vision_quality=90, vision_resolution_ladder=(768,), vision_preserve_canvas=False, model_image_limit=args.image_limit, memory_harness='trajectory', retrieval_max_passes=args.retrieval_passes, retrieval_max_images=args.retrieval_images, memory_archive_dir=str(case / 'memory_archive'), episode_checkpoint_path=str(case / 'checkpoint.json'))
                trace = sim.exploration_evidence()
                evidence = judge(spec, trace, score.success)
                inherited = meta.get('inherited_gateway_usage', {})
                row = {'scene': scene, 'task_id': spec.task.task_id, 'family': spec.family, 'score': score.to_dict(), 'A': bool(score.success), 'N': evidence['necessary_evidence']['status'] == 'pass', 'S': evidence['sufficient_evidence']['status'] == 'pass', 'T': bool(evidence['strict_success']), 'evidence': evidence, 'elapsed_seconds': time.monotonic() - started, 'usage': {'prompt_tokens': client.prompt_tokens - usage_before[0] + inherited.get('prompt_tokens', 0), 'completion_tokens': client.completion_tokens - usage_before[1] + inherited.get('completion_tokens', 0)}, 'client_statistics': client.stats()}
                row['scene_variant'] = spec.scene_variant
                save(case / 'trajectory.json', {'task_id': spec.task.task_id, 'scene_variant': spec.scene_variant, 'meta': meta, 'rounds': agent.rounds, 'exploration_trace': trace})
                result['results'].append(row)
                save(args.output, result)
                print(json.dumps({'completed': len(result['results']), 'selected': len(chosen), 'scene': scene, 'task_id': spec.task.task_id, 'A': row['A'], 'T': row['T']}), flush=True)
    finally:
        harness.episode_for = base_episode
        sim.close()
    return 0
if __name__ == '__main__':
    raise SystemExit(main())
